/** نص السياسات المُنسَّق للـ System Prompt في الخادم */
export function getPoliciesText(): string {
  return Object.entries(STORE_POLICIES)
    .map(([_, policy]) => `• ${policy.title}: ${policy.details.join('؛ ')}`)
    .join('\n');
}

/** نص الأسئلة الشائعة المُنسَّق للـ System Prompt في الخادم */
export function getFaqsText(): string {
  return FAQ_POLICIES.map(f => `س: ${f.question}\nج: ${f.answer}`).join('\n\n');
}
